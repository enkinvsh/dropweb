// Вторичный текст карточки главной: «живой» вторичный уровень поверх стекла.
//
// HIG (materials.md:44): «используйте живые (vibrant) цвета поверх материалов» — плоский серый
// символ на материале дан там как нечитаемый пример. Вторичный ярлык системы это основной цвет
// текста с пониженной непрозрачностью, через которую просвечивает материал, а не фиксированный
// серый. Доска берёт `--glass-label-2` (плоский #8A8A8A тёмной темы, tokens.css:71), и на живом
// стекле iOS 26+ он почти не виден (скриншот владельца 30.10 18:16, просьба «мб белым сделаем
// по hig»). Поэтому карточка красит вторичный текст основным цветом стекла с альфой: белый 0.80
// в тёмной теме и чёрный 0.70 в светлой — иерархия с заголовком сохраняется. Токены вынесены сюда,
// а не в `tokens.g.dart`: тот генерируется из `tokens.css` канона, и этих цветов там нет.

import 'dart:ui' show Color;

/// Цвета вторичного текста карточки главной.
abstract final class Ios27CardColors {
  /// Тёмная тема: белый, альфа 0.80.
  static const Color secondaryDark = Color.fromRGBO(255, 255, 255, 0.80);

  /// Светлая тема: чёрный, альфа 0.70.
  static const Color secondaryLight = Color.fromRGBO(0, 0, 0, 0.70);

  /// Таймер, строка плана, «Подключение…», «—», слово статуса и спиннер страны.
  static Color secondary({required bool dark}) =>
      dark ? secondaryDark : secondaryLight;
}
